const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  platform: process.platform,
  micAccess: () => ipcRenderer.invoke('mic:access'),
  openJw: url => ipcRenderer.invoke('jw:open', url),
  grabTimetable: () => ipcRenderer.invoke('jw:grab'),
  jwLoginStart: () => ipcRenderer.invoke('jw:loginStart'),
  jwCaptcha: () => ipcRenderer.invoke('jw:captcha'),
  jwLoginSubmit: form => ipcRenderer.invoke('jw:loginSubmit', form),
  jwLoginCancel: () => ipcRenderer.invoke('jw:loginCancel'),
  jwLogout: () => ipcRenderer.invoke('jw:logout'),
  pinGuide: () => ipcRenderer.invoke('app:pinGuide'),
  credGet: () => ipcRenderer.invoke('cred:get'),
  credSet: c => ipcRenderer.invoke('cred:set', c),
  portalBegin: () => ipcRenderer.invoke('portal:begin'),
  portalCall: (op, arg) => ipcRenderer.invoke('portal:call', op, arg),
  portalEnd: () => ipcRenderer.invoke('portal:end'),
  asrStart: file => ipcRenderer.invoke('asr:start', webUtils.getPathForFile(file)),
  asrStartPath: p => ipcRenderer.invoke('asr:start', p),
  recBegin: () => ipcRenderer.invoke('rec:begin'),
  recAppend: (id, buf) => ipcRenderer.invoke('rec:append', id, buf),
  recEnd: id => ipcRenderer.invoke('rec:end', id),
  notify: n => ipcRenderer.invoke('app:notify', n),
  getPrefs: () => ipcRenderer.invoke('app:getPrefs'),
  setPrefs: p => ipcRenderer.invoke('app:setPrefs', p),
  asrCancel: () => ipcRenderer.invoke('asr:cancel'),
  onAsr: cb => ipcRenderer.on('asr:event', (_e, m) => cb(m)),
  aiGet: () => ipcRenderer.invoke('ai:get'),
  aiSet: c => ipcRenderer.invoke('ai:set', c),
  aiChat: (messages, id, override) => ipcRenderer.invoke('ai:chat', { messages, id, override }),
  aiCancel: () => ipcRenderer.invoke('ai:cancel'),
  onAiDelta: cb => ipcRenderer.on('ai:delta', (_e, m) => cb(m)),
  onPetAsk: cb => ipcRenderer.on('pet:ask', (_e, m) => cb(m)),
  petReply: (id, r) => ipcRenderer.invoke('pet:reply', id, r),
  setTheme: t => ipcRenderer.send('app:theme', t),
  dataChanged: () => ipcRenderer.send('app:dataChanged'),
  widgetsList: () => ipcRenderer.invoke('widgets:list'),
  widgetsAdd: type => ipcRenderer.invoke('widgets:add', type),
  widgetsUpdate: (id, patch) => ipcRenderer.invoke('widgets:update', id, patch),
  widgetsRemove: id => ipcRenderer.invoke('widgets:remove', id),
  widgetsSetOff: off => ipcRenderer.invoke('widgets:setOff', off),
  widgetsLocate: id => ipcRenderer.invoke('widgets:locate', id),
  onWidgetsChanged: cb => ipcRenderer.on('widgets:changed', () => cb()),
  onWidgetsEdit: cb => ipcRenderer.on('widgets:edit', (_e, id) => cb(id)),
  winCtl: a => ipcRenderer.send('win:ctl', a),
  onWinState: cb => ipcRenderer.on('win:state', (_e, s) => cb(s))
});
